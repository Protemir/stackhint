export function matchPackage(rules: PackageRule[], name: string): Array<[string, number]> {
  const n = name.toLowerCase();
  const out: Array<[string, number]> = [];
  for (const [pattern, signals] of rules) {
    const p = pattern.toLowerCase();
    const hit = p.endsWith('*') ? n.startsWith(p.slice(0, -1)) : n === p;
    if (hit) out.push(...signals);
  }
  return out;
}

